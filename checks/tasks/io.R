# Reading and writing data files: Excel, SPSS, Stata, CSV, with value labels and non-ASCII (Cyrillic) text.
d <- patients(200)
# Cyrillic text, written with escapes because code files are English only
d$comment <- rep(c("\u043d\u0435\u0442", "\u0434\u0430, \u0441\u043b\u0443\u0447\u0430\u0439 \u2116 5", "ok"), length.out = nrow(d))

# Excel: openxlsx writes a styled workbook with two sheets, readxl and openxlsx read it back
xlsx <- file.path(work, "data.xlsx")
wb <- openxlsx::createWorkbook()
openxlsx::addWorksheet(wb, "patients")
openxlsx::writeDataTable(wb, "patients", d)
openxlsx::addWorksheet(wb, "summary")
openxlsx::writeData(wb, "summary", aggregate(y ~ group, d, mean))
openxlsx::saveWorkbook(wb, xlsx, overwrite = TRUE)
check(identical(readxl::excel_sheets(xlsx), c("patients", "summary")), "Excel sheet names")
x <- readxl::read_excel(xlsx, sheet = "patients")
check(nrow(x) == nrow(d) && identical(x$comment, d$comment), "Excel round trip keeps rows and Cyrillic text")
check(isTRUE(all.equal(x$y, d$y)), "Excel round trip keeps numbers")
check(identical(as.Date(x$enrolled), d$enrolled), "Excel round trip keeps dates")
check(identical(openxlsx::read.xlsx(xlsx, sheet = 1)$id, d$id), "openxlsx reads its own file")

# SPSS and Stata with value and variable labels (haven, labelled)
s <- d[, c("id", "group", "age", "sex", "comment")]
s$group <- haven::labelled(as.integer(s$group), c(control = 1L, treatment = 2L))
s <- labelled::set_variable_labels(s, age = "Age, years", comment = "\u041a\u043e\u043c\u043c\u0435\u043d\u0442\u0430\u0440\u0438\u0439")
sav <- file.path(work, "data.sav")
haven::write_sav(s, sav)
r <- haven::read_sav(sav)
check(identical(labelled::var_label(r$age), "Age, years"), "SPSS variable label")
check(identical(labelled::var_label(r$comment), "\u041a\u043e\u043c\u043c\u0435\u043d\u0442\u0430\u0440\u0438\u0439"), "SPSS Cyrillic variable label")
check(identical(as.character(haven::as_factor(r$group)), as.character(d$group)), "SPSS value labels to factor")
check(identical(as.vector(r$comment), d$comment), "SPSS Cyrillic values")
dta <- file.path(work, "data.dta")
haven::write_dta(s, dta)
check(identical(as.character(haven::as_factor(haven::read_dta(dta)$group)), as.character(d$group)), "Stata value labels")
lt <- labelled::look_for(r)
check(nrow(lt) == ncol(s), "labelled::look_for lists every variable")

# CSV: readr and data.table, UTF-8 and semicolon-separated (Excel in many locales)
csv <- file.path(work, "data.csv")
readr::write_csv(d, csv)
r <- readr::read_csv(csv, show_col_types = FALSE)
check(identical(r$comment, d$comment) && identical(r$enrolled, d$enrolled), "readr round trip")
readr::write_csv2(d, csv)
r <- suppressMessages(readr::read_csv2(csv, show_col_types = FALSE))
check(isTRUE(all.equal(r$y, d$y)), "readr round trip with decimal comma")
data.table::fwrite(d, csv)
r <- data.table::fread(csv, encoding = "UTF-8")
check(identical(r$comment, d$comment) && isTRUE(all.equal(r$y, d$y)), "data.table round trip")

record("rows", nrow(d))
record("mean_y", mean(d$y))
